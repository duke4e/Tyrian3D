def frame_shades(f):
    """The frame's pixels: an array of shades (rows from the top, 28 x 24), nan where transparent."""
    rows = FRAMES[f].strip("\n").splitlines()
    return np.array([[np.nan if ch == "." else float(int(ch, 16)) for ch in r] for r in rows])


def pixel_xy(r, c):
    """The middle of the whole's pixel at row r, column c (x right, y up, the origin at the four pieces' corner)."""
    return c + 0.5 - 12.0, 13.5 - r


def outline(S):
    """The frame's outline (its pixels' edges row by row), smoothed: a closed polygon."""
    rows = []
    for r in range(S.shape[0]):
        cols = np.where(~np.isnan(S[r]))[0]
        if len(cols):
            rows.append((r, int(cols[0]), int(cols[-1])))
    right = [(c1 + 1 - 12.0, 13.5 - r) for r, _, c1 in rows]
    left = [(c0 - 12.0, 13.5 - r) for r, c0, _ in rows]
    (r0, a0, b0), (r1, a1, b1) = rows[0], rows[-1]
    points = [((a0 + b0 + 1) / 2 - 12.0, 14.0 - r0)] + right + [((a1 + b1 + 1) / 2 - 12.0, 13.0 - r1)] + left[::-1]
    return mk.chaikin(points, iterations=3)


def smoothed(S, sigma):
    """The shades blurred (a Gaussian of sigma pixels) within the sprite (nan outside)."""
    mask = (~np.isnan(S)).astype(float)
    v = np.nan_to_num(S) * mask
    reach = int(3 * sigma) + 1
    g = np.exp(-np.arange(-reach, reach + 1) ** 2 / (2.0 * sigma * sigma))

    def blur(a):
        a = np.apply_along_axis(lambda m: np.convolve(m, g, mode="same"), 0, a)
        return np.apply_along_axis(lambda m: np.convolve(m, g, mode="same"), 1, a)
    num, den = blur(v), blur(mask)
    return np.where(mask > 0, num / np.maximum(den, 1e-9), np.nan)


def sample(field, x, y):
    """The field (rows from the top) at a point, bilinear; outside the sprite the nearest pixel's."""
    c, r = x + 12.0 - 0.5, 13.5 - y
    c0, r0 = int(math.floor(c)), int(math.floor(r))
    total, weight = 0.0, 0.0
    for dr in (0, 1):
        for dc in (0, 1):
            rr, cc = r0 + dr, c0 + dc
            if 0 <= rr < field.shape[0] and 0 <= cc < field.shape[1] and not np.isnan(field[rr, cc]):
                w = (1 - abs(r - rr)) * (1 - abs(c - cc))
                total += w * field[rr, cc]
                weight += w
    if weight > 1e-6:
        return total / weight
    rr, cc = np.where(~np.isnan(field))
    i = int(np.argmin((rr - r) ** 2 + (cc - c) ** 2))
    return float(field[rr[i], cc[i]])


class RayHeat:
    """A heat round a middle that falls outwards: profile(phi, u) (u: 0 the middle, 1 the rim) sampled on rays and made
    monotone (each ray's running minimum, less a little more at every step: kit.crossings takes the first of equal
    peaks for the hottest, and a plateau there would leave a band's border off the middle), interpolated."""

    def __init__(self, profile, rays=72, steps=40):
        self.rays, self.steps = rays, steps
        self.table = []
        for j in range(rays):
            phi = 2 * math.pi * j / rays
            low, line = 1e9, []
            for i in range(steps + 1):
                low = min(low, profile(phi, i / steps))
                line.append(low - 0.004 * i)
            self.table.append(line)

    def __call__(self, u, phi):
        a = (phi % (2 * math.pi)) / (2 * math.pi) * self.rays
        j = int(a) % self.rays
        s = a - int(a)
        b = min(max(u, 0.0), 1.0) * self.steps
        i = min(int(b), self.steps - 1)
        t = b - i
        row0, row1 = self.table[j], self.table[(j + 1) % self.rays]
        v0 = row0[i] * (1 - t) + row0[i + 1] * t
        v1 = row1[i] * (1 - t) + row1[i + 1] * t
        return v0 * (1 - s) + v1 * s


class Frame:
    """One frame's flame: its outline, heat, size, bed and billows."""

    def __init__(self, f):
        self.f = f
        self.S = frame_shades(f)
        self.F = smoothed(self.S, SIGMA)
        self.C = smoothed(self.S, SIGMA_BED)
        self.poly = outline(self.S)
        rr, cc = np.where(~np.isnan(self.S))
        self.pixels = [pixel_xy(r, c) + (self.S[r, c],) for r, c in zip(rr, cc)]
        self.area = float(len(self.pixels))
        self.radius = math.sqrt(self.area / math.pi)
        # The hot spot: the coarse heat's hottest pixels (weighted); the bed is built round it.
        top = float(np.nanmax(self.C))
        hot = [(x, y, sample(self.C, x, y)) for x, y, _ in self.pixels]
        hot = [(x, y, h - (top - 0.8)) for x, y, h in hot if h > top - 0.8]
        total = sum(w for _, _, w in hot)
        self.hot = (sum(x * w for x, _, w in hot) / total, sum(y * w for _, y, w in hot) / total)
        self.bed_radius = polar(self.poly, self.hot, samples=360)
        self.bed_height = BED_HEIGHT * self.radius

        inner = [sample(self.C, x, y) for x, y, _ in self.pixels
                 if math.hypot(x - self.hot[0], y - self.hot[1]) < 0.5 * self.bed_radius(math.atan2(y - self.hot[1],
                                                                                                      x - self.hot[0]))]
        middle = min(BED_MAX, float(np.mean(inner)) + 0.5)
        rims = []
        for j in range(72):
            phi = 2 * math.pi * j / 72
            d = 0.85 * self.bed_radius(phi)
            rims.append(sample(self.C, self.hot[0] + d * math.cos(phi), self.hot[1] + d * math.sin(phi)))
        rims = [min(middle - 0.3, sum(rims[(j + i) % 72] for i in range(-3, 4)) / 7) for j in range(72)]

        def bed_profile(phi, u):
            a = (phi % (2 * math.pi)) / (2 * math.pi) * 72
            i, t = int(a) % 72, a - int(a)
            rim = rims[i] * (1 - t) + rims[(i + 1) % 72] * t
            return middle - (middle - rim) * min(max(u, 0.0), 1.0) ** BED_FALL
        self.bed_heat = RayHeat(bed_profile)
        self.billows = self.place_billows()

    def bed_heat_xy(self, x, y):
        dx, dy = x - self.hot[0], y - self.hot[1]
        phi = math.atan2(dy, dx)
        return self.bed_heat(math.hypot(dx, dy) / max(self.bed_radius(phi), 1e-6), phi)

    def bed_top(self, x, y):
        dx, dy = x - self.hot[0], y - self.hot[1]
        r = math.hypot(dx, dy)
        if r < 1e-9:
            return self.bed_height
        rho = r / self.bed_radius(math.atan2(dy, dx))
        return self.bed_height * max(0.0, 1.0 - rho * rho) ** BED_POWER

    def place_billows(self):
        """Billows, hottest first: each on the hottest pixel (blurred) no billow covers yet, until they cover
        BILLOW_COVER of the outline or there are as many as the flame's size allows: (x, y, radius, crown heat)."""
        r0 = BILLOW_R0 + BILLOW_RK * self.radius
        most = max(2, int(round(self.area / (math.pi * r0 * r0) * 1.3)))
        points = [(x, y, sample(self.F, x, y)) for x, y, _ in self.pixels]
        billows = []
        while len(billows) < most:
            free = [p for p in points if all(math.hypot(p[0] - b[0], p[1] - b[1]) > BILLOW_APART * 2 * b[2]
                                             for b in billows)]
            if not free:
                break
            x, y, h = max(free, key=lambda p: (p[2], -p[0], p[1]))
            near = max(s for px, py, s in self.pixels if math.hypot(px - x, py - y) < 0.6 * r0)
            crown = max(h + 0.6, h + CROWN * (near - h))
            billows.append((x, y, r0 * (0.85 + 0.3 * min(max((h - 6.0) / 6.0, 0.0), 1.0)), crown))
            covered = sum(1 for px, py, _ in self.pixels
                          if any(math.hypot(px - b[0], py - b[1]) < 0.8 * b[2] for b in billows))
            if covered >= BILLOW_COVER * self.area:
                break
        return billows


def prune(obj):
    """Drops the material slots no face uses."""
    mesh = obj.data
    used = {p.material_index for p in mesh.polygons}
    for i in reversed(range(len(mesh.materials))):
        if i not in used and len(mesh.materials) > 1:
            mesh.materials.pop(index=i)
    return obj


def segments_for(radius, lo, hi, per):
    return int(min(hi, max(lo, round(per * radius))))


def build_bed(name, fr, mats):
    dome = kit.Dome(fr.hot, fr.bed_radius, fr.bed_top, fr.bed_heat, BANDS,
                    segments=segments_for(fr.radius, 12, 22, 2.0), tongues=BED_TONGUES, gap=0.25,
                    middle_fractions=(0.5,), rim_fractions=(0.5, 0.82, 1.0))
    return dome.build(name, mats)


def build_billow(name, fr, billow, mats):
    """A billow: a raised patch on the bed (round its middle, clipped to the outline); its heat the sprite's (blurred,
    never rising outwards from its middle), its crown hotter, its rim as hot as the bed there."""
    bx, by, r, crown = billow
    clip = polar(fr.poly, (bx, by), samples=180)
    lift = BILLOW_LIFT * r

    def radius(phi):
        return min(r * (1.0 + 0.08 * math.sin(phi)), 0.94 * clip(phi))

    def top(x, y):
        dx, dy = x - bx, y - by
        d = math.hypot(dx, dy)
        rho = d / max(radius(math.atan2(dy, dx)), 1e-6) if d > 1e-9 else 0.0
        return fr.bed_top(x, y) + lift * max(0.0, 1.0 - rho * rho) ** 0.5
    centre = sample(fr.F, bx, by)

    def profile(phi, u):
        x, y = bx + u * radius(phi) * math.cos(phi), by + u * radius(phi) * math.sin(phi)
        own = sample(fr.F, x, y) + (crown - centre) * (1.0 - u) ** 1.5
        w = mk.smoothstep(0.6, 1.0, u)
        return own * (1 - w) + fr.bed_heat_xy(x, y) * w
    heat = RayHeat(profile, rays=48, steps=30)
    segs = 10 if r >= 3.0 else 8
    dome = kit.Dome((bx, by), radius, top, heat, BANDS, segments=segs, tongues=(3, 0.04, 1.0), gap=0.3,
                    middle_fractions=(0.45,), rim_fractions=(0.55, 1.0))
    return dome.build(name, mats)


def build_whole(f):
    """The frame's flame whole: (Frame, bed, [billows], materials)."""
    fr = Frame(f)
    mats = kit.materials("zflame_fire", BANDS)
    bed = prune(build_bed("zflame_%d_bed" % f, fr, mats))
    billows = [prune(build_billow("zflame_%d_billow%d" % (f, i), fr, b, mats)) for i, b in enumerate(fr.billows)]
    return fr, bed, billows, mats


def piece_of(x, y):
    """The piece (its first frame's sprite) whose box holds the point."""
    for first, (x0, x1, y0, y1) in PIECES:
        if x0 <= x < x1 and y0 <= y < y1:
            return first
    return min(PIECES, key=lambda p: math.hypot(x - (p[1][0] + p[1][1]) / 2, y - (p[1][2] + p[1][3]) / 2))[0]


def cut_open(source, box_xy):
    """The part of an object inside box (x0, x1, y0, y1), its normals the uncut object's (polish_machine_kit.cut without
    the caps: the four pieces are always drawn together, so the cuts are never seen, and caps were a fifth of a frame's
    triangles). None if nothing is inside."""
    import bmesh
    x0, x1, y0, y1 = box_xy
    obj = source.copy()
    obj.data = source.data.copy()
    bpy.context.scene.collection.objects.link(obj)
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    planes = (((x0, 0, 0), (-1, 0, 0)), ((x1, 0, 0), (1, 0, 0)), ((0, y0, 0), (0, -1, 0)), ((0, y1, 0), (0, 1, 0)))
    for co, no in planes:
        if not bm.faces:
            break
        bmesh.ops.bisect_plane(bm, geom=bm.verts[:] + bm.edges[:] + bm.faces[:], dist=1e-6, plane_co=co, plane_no=no,
                               clear_outer=True)
    if not bm.faces:
        bm.free()
        bpy.data.objects.remove(obj)
        return None
    bm.to_mesh(obj.data)
    bm.free()
    shading = mk.NormalSource(source)
    mesh = obj.data
    normals = []
    for poly in mesh.polygons:
        for li in poly.loop_indices:
            n = shading.normal(mesh.vertices[mesh.loops[li].vertex_index].co, poly.center)
            normals.append(tuple(n if n is not None else poly.normal))
    mesh.normals_split_custom_set(normals)
    return prune(obj)


def pieces(f, fr, bed, billows):
    """The flame in its four sprites' pieces, each moved onto its sprite's centre: the bed cut along the sprites'
    edges, each billow whole in the piece that holds its middle (the four are always drawn together). {sprite:
    [objects]}"""
    out = {}
    for first, box in PIECES:
        cx, cy = (box[0] + box[1]) / 2, (box[2] + box[3]) / 2
        parts = []
        piece = cut_open(bed, box)
        if piece is not None:
            piece.name = "%s_b%d" % (bed.name, first + f)
            parts.append(piece)
        for obj, b in zip(billows, fr.billows):
            if piece_of(b[0], b[1]) == first:
                copy = obj.copy()
                copy.data = obj.data.copy()
                bpy.context.scene.collection.objects.link(copy)
                copy.name = "%s_b%d" % (obj.name, first + f)
                parts.append(copy)
        for p in parts:
            p.data.transform(Matrix.Translation((-cx, -cy, 0.0)))
        out[first + f] = parts
    return out


# The glow (glow=), one a flame, on its top left piece (the four are drawn together): as wide as the flame and 6
# pixels more, GLOW_STRENGTH from the first frame to the last (the fire dying), in GLOW_COLOUR, on the hot spot.
GLOW_STRENGTH = (0.4, 0.2)
GLOW_COLOUR = 0x7a


def cfg_lines(f, fr, height):
    """The frame's models.cfg lines: [model lines], [shot lines]."""
    models, shots = [], []
    last = max(FRAMES)
    strength = GLOW_STRENGTH[0] + (GLOW_STRENGTH[1] - GLOW_STRENGTH[0]) * f / last
    for i, (first, box) in enumerate(PIECES):
        sprite = first + f
        name = "shot_zflame_%d" % sprite
        models.append("model %-16s shots/%s.glb origin" % (name, name))
        cx, cy = (box[0] + box[1]) / 2, (box[2] + box[3]) / 2
        if i == 0:
            glow = "glow=%d:%.2f:%d:%.2f:%.2f" % (round(2 * fr.radius + 6), strength, GLOW_COLOUR, fr.hot[0] - cx,
                                                  cy - fr.hot[1])
        else:
            glow = "glow=1:0"
        shots.append("shot shots2 %d %-16s height=%.2f %s" % (sprite, name, -height / 2, glow))
    return models, shots


def build():
    options = k.args()
    only = set(options["only"].split(",")) if "only" in options else None
    frames = [int(v) for v in options["frames"].split(",")] if "frames" in options else sorted(FRAMES)
    outdir = options.get("outdir", kit.OUTDIR)
    sheets = options.get("check")
    for f in frames:
        names = ["shot_zflame_%d" % (first + f) for first, _ in PIECES]
        if only is not None and not any(n in only for n in names):
            continue
        k.reset()
        fr, bed, billows, mats = build_whole(f)
        whole = triangulate([bed] + billows)
        bpy.context.view_layer.update()
        height = max(v.co.z for o in whole for v in o.data.vertices)
        print("== frame %d: radius %.2f, hot spot %.2f %.2f, %d billows %s; whole %d triangles, height %.2f" % (
            f, fr.radius, fr.hot[0], fr.hot[1], len(fr.billows),
            " ".join("(%.1f %.1f r%.1f h%.1f)" % b for b in fr.billows), mk.triangles(whole), height))
        if "cfg" in options:
            models, shots = cfg_lines(f, fr, height)
            with open(options["cfg"], "a") as out:
                out.write("\n".join(models + shots) + "\n")
        if sheets:
            sheet = os.path.join(sheets, "shots2.png")
            tl, tr, bl, br = [k.sprite_mask(sheet, first + f, large=False) for first, _ in PIECES]
            m = [a + b for a, b in zip(tl, tr)] + [a + b for a, b in zip(bl, br)]
            mk.compare("whole frame %d" % f, mk.coverage(whole, 24, 28), m)
        if "preview" in options:
            bpy.context.scene.view_settings.view_transform = "Standard"
            view(options["preview"] + "zflame_%d_whole" % f, whole, size=(24, 28))
        cut = pieces(f, fr, whole[0], whole[1:])
        for o in whole + [o for parts in cut.values() for o in parts]:
            o.hide_render = True
        for sprite, parts in cut.items():
            name = "shot_zflame_%d" % sprite
            if only is not None and name not in only:
                continue
            for o in parts:
                o.hide_render = False
            if sheets:
                mk.compare("%s (shots2 %d)" % (name, sprite), mk.coverage(parts, 12, 14),
                           k.sprite_mask(os.path.join(sheets, "shots2.png"), sprite, large=False))
            bpy.context.scene.view_settings.view_transform = "Standard"
            mk.report(name, parts, os.path.join(outdir, name + ".glb"))
            if "preview" in options and "pieces" in options:
                view(options["preview"] + name, parts)
            for o in parts:
                o.hide_render = True


if __name__ == "__main__":
    build()
