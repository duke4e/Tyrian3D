# The comet's frames: the pieces' (model, sprite, art) for the tail above and the head below.
FRAMES = [
    (("comet_tail", 203, TAIL_203), ("comet_head", 241, HEAD_241)),
    (("comet_tail_205", 205, TAIL_205), ("comet_head_243", 243, HEAD_243)),
]
# Where each piece lies in the whole (x0, x1, y0, y1): the tail above the junction, the head below.
TAIL_BOX, HEAD_BOX = (-12.0, 12.0, 0.0, 28.0), (-12.0, 12.0, -28.0, 0.0)
# The body: as polish_flame_drop.py's drop, a little flatter (a comet, not a drop), its tail's point
# half a pixel past the tail's top pixel.
DEPTH = (0.66, 0.5)
STEP = 0.42      # the rings' spacing (a longer body than the drop's)
CAP = 0x7c       # the cut's colour (the fire's inside): its band's material


def whole(tail_art, head_art, bands):
    rows = fire.grid(tail_art) + fire.grid(head_art)
    outline = fire.Outline(rows, 28.0)
    heat = fire.Heat(rows, 28.0)
    # Its underside on z = 0: the axis as high as the widest section's depth below it.
    widest = max(outline.width(outline.y0 + (outline.y1 - outline.y0) * i / 400) for i in range(401))
    return fire.fire_body("comet", outline, heat, bands, depth=DEPTH, step=STEP, axis_z=widest * DEPTH[1] + 0.05)


def mask(sheet, tail, head):
    """The two sprites' silhouettes, the tail above the head: 24 x 56."""
    return k.sprite_mask(sheet, tail) + k.sprite_mask(sheet, head)


def build():
    options = k.args()
    only = set(options["only"].split(",")) if "only" in options else None
    out = mk.outdir(options)
    sheet = os.path.join(options["check"], "enemy_5.png") if "check" in options else None
    for (tail_name, tail_sprite, tail_art), (head_name, head_sprite, head_art) in FRAMES:
        if only is not None and tail_name not in only and head_name not in only:
            continue
        k.reset()
        bands = fire.fire_materials("comet")
        cap = next(mat for _, mat in bands if mat.name.endswith("@%d" % CAP))
        body = whole(tail_art, head_art, bands)
        print("whole comet (%d above %d): %d triangles" % (tail_sprite, head_sprite, mk.triangles([body])))
        if sheet:
            mk.compare("whole (%d above %d)" % (tail_sprite, head_sprite), mk.coverage([body], 24, 56),
                       mask(sheet, tail_sprite, head_sprite))
        if "preview" in options:
            mk.preview(options["preview"] + tail_name.replace("tail", "whole"), [body], size=(24, 56), scale=8,
                       distance=2.0)
        for name, sprite, box in ((tail_name, tail_sprite, TAIL_BOX), (head_name, head_sprite, HEAD_BOX)):
            if only is not None and name not in only:
                continue
            piece = mk.cut(body, box, cap)
            piece.name = name
            piece.data.transform(Matrix.Translation((-(box[0] + box[1]) / 2, -(box[2] + box[3]) / 2, 0.0)))
            if sheet:
                mk.compare("%s (5 %d)" % (name, sprite), mk.coverage([piece], 24, 28), k.sprite_mask(sheet, sprite))
            bpy.context.scene.view_settings.view_transform = "Standard"  # previews in the game's colours
            mk.report(name, [piece], os.path.join(out, name + ".glb"))
            if "preview" in options:
                mk.preview(options["preview"] + name, [piece])
            bpy.data.objects.remove(piece)


if __name__ == "__main__":
    build()
