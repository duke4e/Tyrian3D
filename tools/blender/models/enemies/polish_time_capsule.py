def picture(text):
    return Pic(parse(text), LEFT, TOP)


class Capsule:
    def __init__(self, pic):
        self.pic = pic
        a = pic.a
        own = a >= 0
        self.own = own
        self.region = Region(pic, own, sigma=0.5)
        rows = {}
        for r in range(pic.h):
            cols = np.nonzero(own[r])[0]
            if len(cols):
                rows[r] = ((cols[0] + cols[-1] + 1) / 2.0, (cols[-1] + 1 - cols[0]) / 2.0)
        sm = {}
        for r in rows:
            near = [rows[q] for q in range(r - 2, r + 3) if q in rows]
            sm[r] = (sum(v[0] for v in near) / len(near), max(1.0, sum(v[1] for v in near) / len(near)))
        rr = np.arange(pic.h)
        self.mid = np.array([sm.get(r, (AXIS_C, 1.0))[0] for r in rr])
        self.half = np.array([sm.get(r, (AXIS_C, 1.0))[1] for r in rr])
        shade = np.where(own, a & 15, 0)
        dark = own & (a >> 4 == 0) & (shade <= 1)
        h, w = a.shape
        p = np.pad(own, 1)
        surrounded = np.ones_like(own)
        for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            surrounded &= p[1 + dr:1 + dr + h, 1 + dc:1 + dc + w]
        self.crease = blur((dark & surrounded).astype(float), 0.45)
        self.pane = blur((own & (a >> 4 == 9)).astype(float), 0.4)

    def row_shape(self, R):
        f = np.clip(R - 0.5, 0.0, self.pic.h - 1.001)
        r0 = np.floor(f).astype(int)
        t = f - r0
        r1 = np.minimum(r0 + 1, self.pic.h - 1)
        return self.mid[r0] * (1 - t) + self.mid[r1] * t, self.half[r0] * (1 - t) + self.half[r1] * t

    def heights(self, X, Y):
        X, Y = np.asarray(X, float), np.asarray(Y, float)
        C, R = X - LEFT, TOP - Y
        d = self.region.depth(X, Y)
        cc, hw = self.row_shape(R)
        h = HEIGHT * np.clip(hw / 23.5, 0.0, 1.0) ** 0.5
        q = np.clip(1.0 - ((C - cc) / (hw + 0.3)) ** 2, 0.0, 1.0)
        z = h * np.sqrt(q)
        u = np.abs(C - AXIS_C)

        def band(r, r0, r1, soft=0.6):
            return smoothstep(r0 - soft, r0 + soft, r) * (1.0 - smoothstep(r1 - soft, r1 + soft, r))
        (s0, s1), (sr0, sr1), sh = SPINE
        z = z + sh * band(R, sr0, sr1) * band(C, s0, s1, 0.5)
        (c0, c1), ch = COLLAR
        z = z + ch * band(R, c0, c1)
        (w0, w1), wd = WINDOWS
        z = z - wd * band(R, w0, w1) * self.pic.sample(self.pane, X, Y)
        (b0, b1), (br0, br1), bh = BLOCK
        z = z + bh * band(C, b0, b1, 0.4) * band(R, br0, br1, 0.4)
        (k0, k1), (kr0, kr1), kd = CHANNEL
        z = z - kd * band(C, k0, k1, 0.5) * band(R, kr0, kr1)
        z = z - CREASE * self.pic.sample(self.crease, X, Y) * np.clip(z / 4.0, 0.0, 1.0)
        z = z * round_rise(d, EDGE)
        return np.where(d > 0, np.maximum(z, 0.0), 0.0)


def zones(pic):
    a = pic.a
    own = a >= 0
    glass = own & (a >> 4 == 9)
    glint = own & (a >> 4 == 3) & ((a & 15) >= 12)
    return [Zone("grey", own & ~glass & ~glint, GREY, FINISH["grey"], values=np.where(own, a & 15, 0).astype(float)),
            Zone("glass", glass, GLASS, FINISH["glass"], glow=GLASS_GLOW, sigma=0.6, lift=0.6, comp=1.0),
            Zone("glint", glint, GLINT, FINISH["glass"], glow=GLINT_GLOW, sigma=0.5, lift=0.0, comp=0.4),
            Zone("dark", own, [0x01, 0x02], FINISH["dark"], lift=0.0, comp=0.0, pick=False)]


def plate_keys(painter):
    def keys(obj, kinds, wall_z):
        centres, normals = nk.face_data(obj)
        near = painter.zone_at(centres[:, 0], centres[:, 1])
        names = ["dark" if kinds[i] != 0 else (near[i] if near[i] in ("glass", "glint") else "grey")
                 for i in range(len(near))]
        out = painter.keys(obj, zones=names)
        return [("dark", 0x01) if kinds[i] != 0 else key for i, key in enumerate(out)]
    return keys


def build():
    options = k.args()
    out = mk.outdir(options)
    only = set(options["only"].split(",")) if "only" in options else None
    shape_pic = picture(CAPSULE_ART)
    for look, text in (("base", CAPSULE_ART), ("f1", CAPSULE_168_ART), ("f2", CAPSULE_250_ART)):
        todo = [(s, c0, r0) for s, c0, r0 in PIECES if s in FRAMES[look] and
                (only is None or "time_capsule_%d" % FRAMES[look][s] in only)]
        if not todo:
            continue
        k.reset()
        pic = picture(text)
        capsule = Capsule(shape_pic)          # the same solid for every frame: its own picture paints it
        plate = nk.gw.Plate((-24.0, 24.0, -56.0, 56.0), capsule.heights, cells=capsule.region.inside)
        painter = Painter(pic, zones(pic), "time_capsule")
        for s, c0, r0 in todo:
            name = "time_capsule_%d" % FRAMES[look][s]
            box = nk.sprite_box(pic, c0, r0)
            pieces = nk.piece_parts(plate, plate_keys(painter), [], box, nk.box_owner(box), name, painter, ("dark", 0x01))
            mask = nk.sprite_mask(pic, c0, r0) if "check" in options else None
            piece = nk.finish(name, pieces, box, out, options, painter, mask=mask, origin=(LEFT + c0 + 12, TOP - r0 - 14))
            bpy.data.objects.remove(piece)


if __name__ == "__main__":
    build()
