def rows(text):
    return [line for line in text.strip("\n").split("\n")]


def jet(name, art, body_index, wing_index, cockpit=None, max_radius=2.4, wing_thickness=1.1):
    k.reset()
    body = k.material(name + "_body", palette=body_index, metallic=0.45, roughness=0.35)
    wings = k.material(name + "_wings", palette=wing_index, metallic=0.4, roughness=0.4)
    r = rows(art)
    s.plate("wings", r, -wing_thickness / 2, wing_thickness / 2, wings, bevel=0.3)
    s.fuselage("fuselage", r, body, max_radius=max_radius)
    if cockpit is not None:
        y, index = cockpit
        glass = k.material(name + "_glass", palette=index, metallic=0.2, roughness=0.1)
        k.smooth(k.ellipsoid("cockpit", (0.0, y, max_radius * 0.55), (1.2, 2.2, 1.0), glass, 12, 8), 60)
    here = os.path.dirname(os.path.abspath(__file__))
    k.export(os.path.join(here, "..", "..", "..", "..", "assets", "models", "enemies", name + ".glb"))


