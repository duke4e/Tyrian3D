def parse(text):
    rows = []
    for line in text.split():
        rows.append([None if line[2 * c:2 * c + 2] == ".." else int(line[2 * c:2 * c + 2], 16)
                     for c in range(len(line) // 2)])
    return rows


class Pic:
    """A picture's pixels placed in the picture's plane: column c's middle at x = left + c + 0.5, row r's at
    y = top - r - 0.5; a (rows, columns) array of palette indices, -1 where there is none."""

    def __init__(self, rows, left, top):
        self.a = np.array([[-1 if v is None else v for v in row] for row in rows])
        self.h, self.w = self.a.shape
        self.left, self.top = float(left), float(top)

    def P(self, c, r):
        return self.left + c + 0.5, self.top - r - 0.5

    def ramp(self, *ramps):
        return (self.a >= 0) & np.isin(self.a >> 4, ramps)

    def any(self, *indices):
        return np.isin(self.a, indices)

    def shade(self):
        return np.where(self.a >= 0, self.a & 15, 0).astype(float)

    def sample(self, field, X, Y):
        """A field of the picture's pixels (bilinear between their middles) at points."""
        fc = np.clip(np.asarray(X, float) - self.left - 0.5, 0.0, self.w - 1.0)
        fr = np.clip(self.top - np.asarray(Y, float) - 0.5, 0.0, self.h - 1.0)
        c0 = np.minimum(np.floor(fc).astype(int), self.w - 2)
        r0 = np.minimum(np.floor(fr).astype(int), self.h - 2)
        tc, tr = fc - c0, fr - r0
        return ((field[r0, c0] * (1 - tc) + field[r0, c0 + 1] * tc) * (1 - tr) +
                (field[r0 + 1, c0] * (1 - tc) + field[r0 + 1, c0 + 1] * tc) * tr)

    def pixel(self, X, Y):
        """The palette index of the pixel under each point (-1 none)."""
        c = np.clip(np.floor(np.asarray(X, float) - self.left).astype(int), 0, self.w - 1)
        r = np.clip(np.floor(self.top - np.asarray(Y, float)).astype(int), 0, self.h - 1)
        return self.a[r, c]


def blur(a, sigma):
    """A Gaussian blur (the edges clamped)."""
    if sigma <= 0:
        return a.astype(float)
    r = int(math.ceil(3 * sigma))
    w = np.exp(-0.5 * (np.arange(-r, r + 1) / sigma) ** 2)
    w /= w.sum()
    p = np.pad(a.astype(float), r, mode="edge")
    h, wd = a.shape
    tmp = sum(w[i] * p[:, i:i + wd] for i in range(2 * r + 1))
    return sum(w[i] * tmp[i:i + h, :] for i in range(2 * r + 1))


def fill(values, known, iterations=24, default=5.0):
    """values where known; the rest each its known neighbours' average, outwards (polish_gyges_bone_eye's
    wall_shade_field's way)."""
    v = np.where(known, values, 0.0).astype(float)
    kn = known.copy()
    h, w = v.shape
    for _ in range(iterations):
        s = np.zeros_like(v)
        n = np.zeros_like(v)
        pv, pk = np.pad(v, 1), np.pad(kn, 1)
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                s += np.where(pk[1 + dr:1 + dr + h, 1 + dc:1 + dc + w], pv[1 + dr:1 + dr + h, 1 + dc:1 + dc + w], 0)
                n += pk[1 + dr:1 + dr + h, 1 + dc:1 + dc + w]
        new = ~kn & (n > 0)
        if not new.any():
            break
        v[new] = s[new] / n[new]
        kn = kn | new
    v[~kn] = default
    return v


def dilate(mask, steps=1, diagonal=True):
    m = mask.copy()
    for _ in range(steps):
        p = np.pad(m, 1)
        h, w = m.shape
        out = m.copy()
        for dr in (-1, 0, 1):
            for dc in (-1, 0, 1):
                if (dr or dc) and (diagonal or not (dr and dc)):
                    out |= p[1 + dr:1 + dr + h, 1 + dc:1 + dc + w]
        m = out
    return m


def erode(mask, steps=1):
    return ~dilate(~mask, steps)


def smoothstep(e0, e1, x):
    t = np.clip((np.asarray(x, float) - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3 - 2 * t)


def smax(a, b, kk):
    """A smooth maximum (blending over kk)."""
    h = np.clip(0.5 + 0.5 * (a - b) / kk, 0.0, 1.0)
    return a * h + b * (1 - h) + kk * h * (1 - h)


class Region:
    """A mask of pixels as a smooth shape: its outline the 0.5 contour of the mask blurred by sigma; depth(): how far a
    point lies inside it (negative: outside)."""

    def __init__(self, pic, mask, sigma=0.55, step=0.25):
        self.pic = pic
        self.soft = blur(mask.astype(float), sigma)
        xs = np.arange(pic.left + step / 2, pic.left + pic.w, step)
        ys = np.arange(pic.top - pic.h + step / 2, pic.top, step)
        X, Y = np.meshgrid(xs, ys)
        inside = pic.sample(self.soft, X, Y) > 0.5
        p = np.pad(inside, 1, mode="edge")
        h, w = inside.shape
        edge = np.zeros_like(inside)
        for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            edge |= p[1 + dr:1 + dr + h, 1 + dc:1 + dc + w] != inside
        self.pts = np.stack([X[edge], Y[edge]], 1)

    def inside(self, X, Y):
        pic = self.pic
        X, Y = np.asarray(X, float), np.asarray(Y, float)
        within = (X >= pic.left) & (X <= pic.left + pic.w) & (Y <= pic.top) & (Y >= pic.top - pic.h)
        return within & (pic.sample(self.soft, X, Y) > 0.5)

    def depth(self, X, Y):
        X, Y = np.asarray(X, float), np.asarray(Y, float)
        flat = np.stack([X.ravel(), Y.ravel()], 1)
        d = np.empty(len(flat))
        for i in range(0, len(flat), 1500):
            q = flat[i:i + 1500]
            d[i:i + 1500] = np.sqrt(((q[:, None, :] - self.pts[None, :, :]) ** 2).sum(-1)).min(1)
        d = d.reshape(X.shape)
        return np.where(self.inside(X, Y), d, -d)


