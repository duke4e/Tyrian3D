def dome(X, Y, centre, radii, height, angle=0.0, power=0.5):
    """An ellipse of the plane raised into a dome (its section an ellipse to the power: 0.5 round)."""
    (x0, y0), (a, b) = centre, radii
    ca, sa = math.cos(math.radians(angle)), math.sin(math.radians(angle))
    u = (X - x0) * ca + (Y - y0) * sa
    v = -(X - x0) * sa + (Y - y0) * ca
    return height * np.clip(1.0 - (u / a) ** 2 - (v / b) ** 2, 0.0, None) ** power


def tube(X, Y, points, power=0.5):
    """A limb lying along a path of the plane: points (x, y, half-width, height), its section an ellipse."""
    out = np.zeros_like(X)
    for (px, py, pw, ph), (qx, qy, qw, qh) in zip(points, points[1:]):
        dx, dy = qx - px, qy - py
        t = np.clip(((X - px) * dx + (Y - py) * dy) / max(1e-9, dx * dx + dy * dy), 0.0, 1.0)
        d = np.hypot(X - (px + t * dx), Y - (py + t * dy))
        w = pw + t * (qw - pw)
        h = ph + t * (qh - ph)
        out = np.maximum(out, h * np.clip(1.0 - (d / w) ** 2, 0.0, None) ** power)
    return out


