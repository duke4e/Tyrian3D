STEM_UNDER = 0.5                  # its underside: this share of its top's height under the axis
FINGER_H = (0.45, 0.3)            # the purple fingers on the stem: how far they stand out, and more per shade
# The cap: its middle (column, row) and radii in the picture's plane, the height of its rim and of its dome over it.
CAP = ((23.5, 23.1), (12.0, 7.6))
CAP_BASE, CAP_H, CAP_POWER = 9.2, 6.0, 0.45
CAP_UNDER = 1.2                   # its underside this far under its rim
