class Plate:
    """A heightfield solid in the picture's plane on the grid STEP apart from GRID0, over box (aligned with it): its
    top top(X, Y) over the cells it holds (cells(X, Y) of their middles), its bottom base(X, Y) (z 0 if none), walls
    between them round its cells."""

    def __init__(self, box, top, base=None, cells=None, bottom=True):
        self.bottom = bottom              # False: no bottom (never seen from above: a plate standing over others)
        self.x0, self.x1, self.y0, self.y1 = box
        self.i0 = int(round((self.x0 - GRID0[0]) / STEP))
        self.j0 = int(round((self.y0 - GRID0[1]) / STEP))
        self.nx = int(round((self.x1 - self.x0) / STEP))
        self.ny = int(round((self.y1 - self.y0) / STEP))
        xs = GRID0[0] + STEP * (self.i0 + np.arange(self.nx + 1))
        ys = GRID0[1] + STEP * (self.j0 + np.arange(self.ny + 1))
        self.X, self.Y = np.meshgrid(xs, ys)
        self.Z = top(self.X, self.Y)
        self.B = base(self.X, self.Y) if base is not None else None
        # The top's normals from the whole heightfield (its slopes), so that pieces cut from it meet without seams.
        gy, gx = np.gradient(self.Z, STEP)
        n = np.stack([-gx, -gy, np.ones_like(gx)], -1)
        self.N = n / np.linalg.norm(n, axis=-1)[..., None]
        cx, cy = self.cell_centres()
        self.cells = cells(cx, cy) if cells is not None else np.ones(cx.shape, bool)

    def cell_centres(self):
        return self.X[:-1, :-1] + STEP / 2, self.Y[:-1, :-1] + STEP / 2

    def mesh(self, name, owns):
        """The cells it holds that owns(X, Y) of their middles accepts, as a closed solid: the top (each cell split
        along its flatter diagonal), walls round them, the bottom (in strips at z 0, or a quad a cell). Returns the
        object, each face's kind (0 top, 1 wall, 2 bottom) and, for the walls, their top edge's middle height; None if
        it holds none of them."""
        cx, cy = self.cell_centres()
        owned = self.cells & owns(cx, cy)
        if not owned.any():
            return None, None, None
        verts, faces, kinds, wall_z = [], [], [], []
        top, low = {}, {}
        B = self.B

        def vt(i, j):
            if (i, j) not in top:
                top[(i, j)] = len(verts)
                verts.append((float(self.X[j, i]), float(self.Y[j, i]), float(self.Z[j, i])))
            return top[(i, j)]

        def vb(i, j):
            if (i, j) not in low:
                low[(i, j)] = len(verts)
                verts.append((float(self.X[j, i]), float(self.Y[j, i]), 0.0 if B is None else float(B[j, i])))
            return low[(i, j)]

        ny, nx = owned.shape
        for j in range(ny):
            for i in range(nx):
                if not owned[j, i]:
                    continue
                a, b, c, d = vt(i, j), vt(i + 1, j), vt(i + 1, j + 1), vt(i, j + 1)
                za, zb, zc, zd = self.Z[j, i], self.Z[j, i + 1], self.Z[j + 1, i + 1], self.Z[j + 1, i]
                if abs(za - zc) <= abs(zb - zd):
                    faces += [(a, b, c), (a, c, d)]
                else:
                    faces += [(a, b, d), (b, c, d)]
                kinds += [0, 0]
                wall_z += [0.0, 0.0]
                for (pi, pj), (qi, qj), (ni, nj) in (((i, j), (i + 1, j), (i, j - 1)),
                                                     ((i + 1, j), (i + 1, j + 1), (i + 1, j)),
                                                     ((i + 1, j + 1), (i, j + 1), (i, j + 1)),
                                                     ((i, j + 1), (i, j), (i - 1, j))):
                    if 0 <= ni < nx and 0 <= nj < ny and owned[nj, ni]:
                        continue
                    faces.append((vt(pi, pj), vb(pi, pj), vb(qi, qj), vt(qi, qj)))
                    kinds.append(1)
                    wall_z.append(0.5 * (self.Z[pj, pi] + self.Z[qj, qi]))
                if B is not None and self.bottom:
                    faces.append((vb(i, j), vb(i, j + 1), vb(i + 1, j + 1), vb(i + 1, j)))
                    kinds.append(2)
                    wall_z.append(0.0)
        if B is None:
            for j in range(ny):
                i = 0
                while i < nx:
                    if not owned[j, i]:
                        i += 1
                        continue
                    i0 = i
                    while i < nx and owned[j, i]:
                        i += 1
                    faces.append((vb(i0, j), vb(i0, j + 1), vb(i, j + 1), vb(i, j)))
                    kinds.append(2)
                    wall_z.append(0.0)
        mesh = bpy.data.meshes.new(name)
        mesh.from_pydata(verts, [], faces)
        mesh.validate()
        obj = bpy.data.objects.new(name, mesh)
        bpy.context.scene.collection.objects.link(obj)
        # Shading: the top smooth with the heightfield's normals, its walls and bottom flat.
        vertex_normal = {index: tuple(self.N[j, i]) for (i, j), index in top.items()}
        mesh.polygons.foreach_set("use_smooth", [True] * len(mesh.polygons))
        loops = []
        for poly, kind in zip(mesh.polygons, kinds):
            for li in poly.loop_indices:
                v = mesh.loops[li].vertex_index
                loops.append(vertex_normal[v] if kind == 0 else tuple(poly.normal))
        mesh.normals_split_custom_set(loops)
        mesh.update()
        return obj, kinds, wall_z


def shear_to_camera(objects):
    """Moves every point along the game camera's line of sight to its height (y - z tan 20), so that the camera sees
    each where the sprite draws it; the normals follow (the shear's inverse transpose; polish_lava_grub.py's)."""
    for obj in objects:
        mesh = obj.data
        normals = [Vector(cn.vector) for cn in mesh.corner_normals]
        for v in mesh.vertices:
            v.co.y -= v.co.z * TAN_T
        mesh.normals_split_custom_set([tuple(Vector((n.x, n.y, n.z + TAN_T * n.y)).normalized()) for n in normals])
        mesh.update()


def ellipsoid(name, centre, radii, mat, count=12, around=32, cut_below=None):
    """An ellipsoid lofted from explicit rings (the same every run), optionally only its part above a height."""
    (cx, cy, cz), (rx, ry, rz) = centre, radii
    rings = []
    lowest = -math.pi / 2
    if cut_below is not None:
        lowest = math.asin(max(-1.0, min(1.0, (cut_below - cz) / rz)))
    for i in range(count):
        p = lowest + (math.pi / 2 - lowest) * i / count
        r, z = math.cos(p), math.sin(p)
        rings.append([Vector((cx + rx * r * math.cos(2 * math.pi * j / around),
                              cy + ry * r * math.sin(2 * math.pi * j / around), cz + rz * z)) for j in range(around)])
    start = None if cut_below is not None else (cx, cy, cz - rz)
    return k.loft(name, rings, mat, cap_start=True, start_point=start, end_point=(cx, cy, cz + rz))


