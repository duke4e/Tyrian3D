def pal(prefix, index, metallic, roughness, glow=0.0):
    extra = dict(emission=k.level_palette()[index], emission_strength=glow) if glow > 0 else {}
    return k.material("%s_%x" % (prefix, index), palette=index, metallic=metallic, roughness=roughness, **extra)


def nearest(value, shades):
    """For each value (a shade, 0-15), the palette index of the list whose shade is nearest."""
    s = np.asarray(shades)
    return s[np.abs(np.asarray(value, float)[..., None] - (s % 16)[None, :]).argmin(-1)]


# --- A creature in a square of tube wall -----------------------------------------------------------------------------

PIT_FLOOR = 0.35                  # small dark gaps' floor (the wall's top is be.SLAB_TOP)
HOLLOW_FLOOR = 0.15               # the floor of the big dark hollows under the creatures
STRAND_H = 0.8                    # how high the wall's dark strands across those hollows stand over their floor
FALL = 1.1                        # how far in from its outline a creature rises to its full height
CREASE = 1.6                      # how deep the sprite's dark lines inside a creature are cut (on its full height)
DETAIL = (0.14, 0.55)             # the sprite's fine shading as relief on the creature: per shade, its limit (pixels)
EDGE_IN = 2.5                     # a creature reaching the square's edge sinks into the wall over this
LIFT = 1.5                        # the creatures painted this many shades lighter than drawn (the game reads darker)
COMP = 2.0                        # and lighter where the game's sun lights them less (LIT_MEAN: on average), so that
LIT_MEAN = 0.72                   # its light and the sprite's drawn light don't add up
GLOW_LIFT = 0.8                   # the lit frames' glowing shades: this much lighter than the frame draws them
SQUARE = (-24.0, 24.0, -28.0, 28.0)


class WallCreature:
    """A creature in a square of GYGES' tube wall, as one heightfield in the picture's plane: the wall's top (the bone
    eye's slab: its tubes' relief from the wall's shades, flat at the square's edges), the sprite's dark hollows sunk
    into it (the wall's dark strands across them), the creature's shapes standing on it (cut down to the sprite's
    outline, its dark lines creased, its fine shading as a little relief)."""

    def __init__(self, pic, core, shapes, box=SQUARE, sink=0.8, detail=DETAIL):
        self.pic, self.box, self.shapes, self.sink, self.detail = pic, box, shapes, sink, detail
        dark = pic.any(0x00, 0x01)
        self.core = core
        self.full = core | (dark & dilate(core, 1))
        h, w = self.full.shape
        p = np.pad(self.full, 1, mode="edge")
        surrounded = np.ones_like(self.full)
        for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            surrounded &= p[1 + dr:1 + dr + h, 1 + dc:1 + dc + w]
        self.internal = dark & self.full & surrounded
        p8 = np.pad(dark, 1)
        neighbours = sum(p8[1 + dr:1 + dr + h, 1 + dc:1 + dc + w].astype(int) for dr in (-1, 0, 1) for dc in (-1, 0, 1)
                         if dr or dc)
        self.pit = dark & ~self.full & (neighbours >= 2)      # dark pixels in a group (not stray dots)
        wall = (pic.ramp(6) | dark) & ~self.full
        shade = pic.shade()
        self.wall_raw = fill(shade, wall)
        self.wall_soft = blur(self.wall_raw, 0.7)
        self.crea_soft = blur(fill(shade, core), 0.6)
        self.crea_broad = blur(fill(shade, core), 2.2)
        self.region = Region(pic, self.full)
        self.pit_soft = blur(self.pit.astype(float), 0.45)
        self.crease = blur(self.internal.astype(float), 0.5)
        # The big hollows (their dark pixels closed over the wall's strands between them) and those strands.
        self.zone = erode(dilate(self.pit, 2), 2) & ~self.full
        self.zone_soft = blur(self.zone.astype(float), 0.6)
        self.strands = self.zone & pic.ramp(6)
        self.strand_region = Region(pic, self.strands, sigma=0.45) if self.strands.any() else None

    def edge(self, X, Y):
        x0, x1, y0, y1 = self.box
        return np.minimum(np.minimum(X - x0, x1 - X), np.minimum(Y - y0, y1 - Y))

    def creature(self, X, Y):
        """The creature's height over the wall's top."""
        pic = self.pic
        X, Y = np.asarray(X, float), np.asarray(Y, float)
        hc = self.shapes(X, Y)
        depth = self.region.depth(X, Y)
        hc = hc * smoothstep(0.0, FALL, depth)
        hc = hc - CREASE * pic.sample(self.crease, X, Y) * np.clip(hc / 3.0, 0.0, 1.0)
        soft = pic.sample(self.crea_soft, X, Y)
        fine = soft - pic.sample(self.crea_broad, X, Y)
        hc = hc + np.clip(self.detail[0] * fine, -self.detail[1], self.detail[1]) * smoothstep(0.3, 1.5, hc)
        hc = hc - self.sink * smoothstep(3.2, 0.8, soft) * np.clip(hc / 3.0, 0.0, 1.0)   # the darkest shading sunk
        hc = hc * smoothstep(0.0, EDGE_IN, self.edge(X, Y))
        return np.where(depth > 0, np.maximum(hc, 0.0), 0.0)

    def wall_top(self, X, Y):
        pic = self.pic
        t = (pic.sample(self.wall_soft, X, Y) - 5.0) / 4.0
        relief = np.clip(be.RELIEF * t, be.RELIEF_LIMITS[0], be.RELIEF_LIMITS[1])
        relief = relief * smoothstep(0.0, be.EDGE_FADE, self.edge(X, Y))
        relief = relief * (1.0 - smoothstep(0.15, 0.6, pic.sample(self.region.soft, X, Y)))
        pit = smoothstep(0.3, 0.7, pic.sample(self.pit_soft, X, Y))
        z = be.SLAB_TOP + relief * (1.0 - pit) - (be.SLAB_TOP - PIT_FLOOR) * pit
        if self.strand_region is not None:
            zone = smoothstep(0.3, 0.75, pic.sample(self.zone_soft, X, Y))
            strand = STRAND_H * np.clip(self.strand_region.depth(X, Y) / 0.8, 0.0, 1.0) ** 0.5
            z = z * (1.0 - zone) + (HOLLOW_FLOOR + strand) * zone
        return z

    def in_hollow(self, X, Y):
        """0: the wall; 1: a hollow's floor; 2: a strand across a hollow."""
        zone = self.pic.sample(self.zone_soft, X, Y) > 0.5
        pit = self.pic.sample(self.pit_soft, X, Y) > 0.5
        strand = self.strand_region.depth(X, Y) > 0.1 if self.strand_region is not None else np.zeros_like(zone)
        return np.where(zone & strand, 2, np.where(zone | pit, 1, 0))

    def heights(self, X, Y):
        return self.wall_top(X, Y) + self.creature(X, Y)

    def plate(self):
        return Plate(self.box, self.heights)


class Ink:
    """One of a creature's colours: the pixels it is drawn in (mask), their shades (filled across the rest, blurred) and
    the materials it is painted with (palette indices of one ramp; glows: indices that glow, with their strengths)."""

    def __init__(self, pic, mask, prefix, shades, finish, sigma=0.85, glows=None):
        self.mask, self.shades = mask, list(shades)
        self.soft = blur(fill(pic.shade(), mask), sigma)
        self.weight = blur(mask.astype(float), 0.6)
        glows = glows or {}
        self.mats = {s: pal(prefix, s, finish[0], finish[1], glows.get(s, 0.0)) for s in self.shades}


class Look:
    """How a frame paints its creature: by the ink drawn nearest each face (the sprite's shades blurred a little,
    lifted, lighter where the game's sun lights the face less), the sprite's dark lines dark; where the frame lights a
    part (lit, a mask of pixels), in glowing shades."""

    def __init__(self, obj, pic, inks, dark, lift=LIFT, comp=COMP, lit=None, glows=(), glow_prefix=None,
                 finish=(0.25, 0.24)):
        self.obj, self.pic, self.inks, self.dark, self.lift, self.comp = obj, pic, inks, dark, lift, comp
        self.core = obj.core | lit if lit is not None else obj.core
        self.lit = blur(lit.astype(float), 0.5) if lit is not None else None
        self.glows = list(glows)
        self.mats = {}
        for ink in inks:
            self.mats.update(ink.mats)
        self.mats[dark[0]] = dark[1]
        for s, strength in self.glows:
            self.mats[("glow", s)] = pal(glow_prefix, s, finish[0], finish[1], glow=strength)

    def key(self, X, Y, hc, on_core, lit_by):
        """The material keys of creature faces at X, Y (hc their height over the wall; on_core: whether the frame draws
        its creature in the pixel under them; lit_by: how much the game's sun lights them)."""
        pic = self.pic
        weights = np.stack([pic.sample(ink.weight, X, Y) for ink in self.inks], 0)
        which = weights.argmax(0)
        crease = pic.sample(self.obj.crease, X, Y)
        lit = pic.sample(self.lit, X, Y) if self.lit is not None else np.zeros(len(X))
        out = []
        per_ink = []
        for ink in self.inks:
            raw = pic.sample(ink.soft, X, Y)
            s = raw + self.lift + self.comp * (LIT_MEAN - lit_by)
            per_ink.append((raw, nearest(s, ink.shades)))
        cut = (self.glows[0][0] & 15) - 2.5 if self.glows else 99.0
        for i in range(len(X)):
            raw, keys = per_ink[which[i]]
            if lit[i] > 0.5 and raw[i] + GLOW_LIFT >= cut:
                # where the frame lights the head: glowing, by the frame's own shade (it lights itself)
                out.append(("glow", min(self.glows, key=lambda g: abs((g[0] & 15) - raw[i] - GLOW_LIFT))[0]))
            elif (hc[i] < 0.25 and not on_core[i]) or crease[i] > 0.5:
                out.append(self.dark[0])
            else:
                out.append(int(keys[i]))
        return out


def hollow_materials(prefix):
    """The dark hollows' floor and the dull strands across them."""
    return {"pit": pal(prefix + "_hollow", 0x60, 0.1, 0.6), "strand": pal(prefix + "_strand", 0x62, 0.1, 0.55)}


def face_data(mesh_obj):
    mesh = mesh_obj.data
    n = len(mesh.polygons)
    centres = np.empty(3 * n)
    normals = np.empty(3 * n)
    mesh.polygons.foreach_get("center", centres)
    mesh.polygons.foreach_get("normal", normals)
    return centres.reshape(n, 3), normals.reshape(n, 3)


def sun_on(normals):
    """How much the game's sun lights faces of the picture's plane (their normals sheared to the camera)."""
    world = normals.copy()
    world[:, 2] += TAN_T * world[:, 1]
    world /= np.maximum(1e-9, np.linalg.norm(world, axis=1))[:, None]
    return np.clip(world @ np.array(SUN), 0.0, 1.0)


def set_materials(mesh_obj, keys, mats):
    """Gives the faces the materials of their keys (only those used, in a fixed order)."""
    mesh = mesh_obj.data
    order = sorted(set(keys), key=lambda key: "%s" % (key,))
    mesh.materials.clear()
    for key in order:
        mesh.materials.append(mats[key])
    slot = {key: i for i, key in enumerate(order)}
    mesh.polygons.foreach_set("material_index", [slot[key] for key in keys])
    mesh.update()


def paint_square(obj, look, mesh_obj, kinds, wall_z, wall_mats, extra):
    """Every face of a square's heightfield its material: the creature's by its look, the hollows dark, the wall by its
    shades (polish_gyges_bone_eye's slab's way: the nearest of its shades to the pixel's); its walls (seen only where a
    neighbour is gone) as the wall going on or the creature's dark inside."""
    centres, normals = face_data(mesh_obj)
    X, Y = centres[:, 0], centres[:, 1]
    pic = obj.pic
    hc = obj.creature(X, Y)
    inside = obj.region.inside(X, Y)
    hollow = obj.in_hollow(X, Y)
    pr = np.clip(np.floor(pic.top - Y).astype(int), 0, pic.h - 1)
    pc = np.clip(np.floor(X - pic.left).astype(int), 0, pic.w - 1)
    on_core = look.core[pr, pc]
    wall_keys = nearest(pic.sample(obj.wall_raw, X, Y) + 0.4, be.WALL_SHADES)
    strand_keys = ["strand" if v > 2.5 else "pit" for v in pic.sample(obj.wall_raw, X, Y)]
    crea_keys = look.key(X, Y, hc, on_core, sun_on(normals))
    mats = dict(wall_mats)
    mats.update(look.mats)
    mats.update(extra)
    keys = []
    for i in range(len(X)):
        if kinds[i] == 2:
            keys.append(be.WALL_SHADES[1])
        elif kinds[i] == 1:
            keys.append(look.dark[0] if wall_z[i] > be.SLAB_TOP + 0.6 else be.WALL_SHADES[1])
        elif inside[i] and (hc[i] > 0.05 or on_core[i]):
            keys.append(crea_keys[i])
        elif hollow[i] == 1:
            keys.append("pit")
        elif hollow[i] == 2:
            keys.append(strand_keys[i])
        else:
            keys.append(int(wall_keys[i]))
    set_materials(mesh_obj, keys, mats)


def piece_owner(box):
    x0, x1, y0, y1 = box
    return lambda cx, cy: (cx >= x0) & (cx < x1) & (cy >= y0) & (cy < y1)


def finish_piece(model, parts, box, out, options):
    """Shears a piece's parts to the camera, moves its sprite's middle to the origin, triangulates and joins them,
    exports it; returns it."""
    shear_to_camera(parts)
    centre = ((box[0] + box[1]) / 2, (box[2] + box[3]) / 2)
    mk.transform(parts, Matrix.Translation((-centre[0], -centre[1], 0.0)))
    bpy.context.view_layer.update()
    triangulate(parts)
    piece = join(parts, model) if len(parts) > 1 else parts[0]
    piece.name = model
    drop_unused([piece])
    bpy.context.scene.view_settings.view_transform = "Standard"
    mk.report(model, [piece], os.path.join(out, model + ".glb"))
    if "preview" in options:
        mk.preview(options["preview"] + model, [piece])
    return piece


def own_coverage(covered_fn, w, h, left, top):
    """Which pixels of a w x h picture (its top left corner at left, top) covered_fn(X, Y) covers (supersampled)."""
    covered = []
    for r in range(h):
        row = []
        for c in range(w):
            xs = left + c + (np.arange(4) + 0.5) / 4
            ys = top - r - (np.arange(4) + 0.5) / 4
            X, Y = np.meshgrid(xs, ys)
            row.append(float(np.asarray(covered_fn(X, Y), float).mean()) > 0.5)
        covered.append(row)
    return covered


def own_check(label, covered_fn, pic, mask):
    """The creature's own pixels as the camera sees them (where it stands over the wall) against the sprite's."""
    return mk.compare(label, own_coverage(covered_fn, pic.w, pic.h, pic.left, pic.top), mask.tolist())


