def picture(text):
    return Pic(parse(text), -12.0, 14.0)


class Capsule:
    def __init__(self, pic):
        self.pic = pic
        a = pic.a
        own = a >= 0
        self.region = Region(pic, own, sigma=0.5)
        shade = np.where(own, a & 15, 0)
        dark = own & (shade <= 3)
        h, w = a.shape
        p = np.pad(own, 1)
        surrounded = np.ones_like(own)
        for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            surrounded &= p[1 + dr:1 + dr + h, 1 + dc:1 + dc + w]
        self.crease = blur((dark & surrounded).astype(float), 0.45)

    def own(self, X, Y):
        X, Y = np.asarray(X, float), np.asarray(Y, float)
        C, R = X + 12.0, 14.0 - Y
        d = self.region.depth(X, Y)
        z = LID[0] * round_rise(d, LID[1])
        (b0, b1), bh = BAND
        z = z + bh * smoothstep(b0 - 0.6, b0 + 0.6, R) * (1.0 - smoothstep(b1 - 0.6, b1 + 0.6, R))
        (s0, s1), (sr0, sr1), sd = SEAM
        z = z - sd * smoothstep(s0 - 0.4, s0 + 0.4, C) * (1.0 - smoothstep(s1 - 0.4, s1 + 0.4, C)) * \
            smoothstep(sr0, sr0 + 1.0, R) * (1.0 - smoothstep(sr1 - 1.0, sr1, R))
        z = z - CREASE * self.pic.sample(self.crease, X, Y) * np.clip(z / 3.0, 0.0, 1.0)
        return np.where(d > 0, np.maximum(z, 0.05), 0.0)


def head_under(head):
    def under(X, Y):
        C, R = np.asarray(X, float) + 12.0 + PLACE[0], 14.0 - np.asarray(Y, float) + PLACE[1]
        return head.top(C + dh.LEFT, dh.TOP - R)
    return under


def build():
    options = k.args()
    out = mk.outdir(options)
    only = set(options["only"].split(",")) if "only" in options else None
    head = dh.Head(dh.picture())
    shape = Capsule(picture(DELI_ART))
    # Raised as a whole onto the jaw's highest points under it (the ridge and the inner bulbs): its sides go down into
    # the jaw, its own shape stands over it.
    cs = np.arange(-12.0 + 0.25, 12.0, 0.5)
    rs = np.arange(-14.0 + 0.25, 14.0, 0.5)
    CX, CY = np.meshgrid(cs, rs)
    inner = shape.region.depth(CX, CY) > 1.0
    lift = float(head_under(head)(CX[inner], CY[inner]).max()) + GAP

    def top(X, Y):
        z = shape.own(X, Y)
        return np.where(z > 0.0, z + lift, 0.0)
    for name, var in FRAMES:
        if only is not None and name not in only:
            continue
        k.reset()
        pic = picture(globals()[var])
        plate = nk.gw.Plate((-12.0, 12.0, -14.0, 14.0), top, cells=shape.region.inside)
        own = pic.a >= 0
        painter = Painter(pic, [Zone("lilac", own, LILAC, FINISH["lilac"], glow=GLOW, lift=1.0),
                                Zone("dark", own, [0x51, 0x52], FINISH["dark"], lift=0.0, comp=0.0, pick=False)],
                          "deli_capsule")

        def keys(obj, kinds, wall_z):
            out_ = painter.keys(obj, zones=["dark" if kd != 0 else "lilac" for kd in kinds])
            return [("dark", 0x51) if kinds[i] != 0 else key for i, key in enumerate(out_)]
        box = (-12.0, 12.0, -14.0, 14.0)
        parts = nk.piece_parts(plate, keys, [], box, nk.box_owner(box), name, painter, ("dark", 0x51))
        mask = nk.sprite_mask(pic, 0, 0) if "check" in options else None
        piece = nk.finish(name, parts, box, out, options, painter, mask=mask, origin=(0.0, 0.0))
        bpy.data.objects.remove(piece)


if __name__ == "__main__":
    build()
